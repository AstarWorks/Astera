/**
 * Generate a Minecraft `/summon item_display` command for an exported effect.
 *
 * The texture is referenced via the `item_model` component (1.21.4+ data-driven
 * item-model system). For an effect exported as
 *   content/textures/animations/<slug>.png + <slug>.mcmeta.json
 * with model
 *   content/models/effects/<slug>.model.json
 * the corresponding resource-pack path is
 *   assets/astera/models/item/effects/<slug>.json   ← the model.json
 *   assets/astera/textures/effects/<slug>.png       ← the animated texture
 *
 * The user pastes the resource pack manually for now; this command line
 * just gives them the in-game summon to verify the hologram looks right.
 *
 * For Bedrock support and older MC versions we may need different generators;
 * for now, Java 1.21.4+ only.
 */
import type { FxGraph } from './types'

export type SummonOptions = {
  /** Effect slug used in textures/animations/<slug>.png + model.json. */
  basename: string
  /** Resource-pack namespace. Defaults to 'astera'. */
  namespace?: string
  /** Position relative to caller. */
  pos?: string
  /** Billboard mode: 'center' / 'fixed' / 'vertical' / 'horizontal'. */
  billboard?: 'center' | 'fixed' | 'vertical' | 'horizontal'
  /** Display scale multiplier. */
  scale?: number
}

/**
 * Produce a paste-ready Java Edition 1.21.4+ summon command.
 *
 * Two-step: a custom item model lookup via the `minecraft:item_model`
 * component, embedded in the carrier item's data on the ItemDisplay.
 * The carrier item itself (paper) is invisible because its model is fully
 * overridden by `astera:effects/<slug>`.
 */
export function summonCommand(opts: SummonOptions): string {
  const ns = opts.namespace ?? 'astera'
  const slug = opts.basename
  const pos = opts.pos ?? '~ ~1 ~'
  const billboard = opts.billboard ?? 'center'
  const scale = opts.scale ?? 1.0
  const s = scale.toFixed(2)

  return `summon minecraft:item_display ${pos} {item:{id:"minecraft:paper",components:{"minecraft:item_model":"${ns}:effects/${slug}"}},billboard:"${billboard}",transformation:{left_rotation:[0f,0f,0f,1f],right_rotation:[0f,0f,0f,1f],translation:[0f,0f,0f],scale:[${s}f,${s}f,${s}f]},brightness:{block:15,sky:15}}`
}

/**
 * Generate a small help / instructions doc to ship next to the artifacts.
 * Written to content/effects/<slug>.summon.txt by the export pipeline.
 */
export function summonHelpFile(graph: FxGraph, basename: string): string {
  const cmd = summonCommand({ basename })
  const slug = basename
  const fps = (20 / graph.frame_time_ticks).toFixed(1)
  return `# Astera Studio — エフェクト「${graph.name}」のインゲーム召喚

## ファイル
- texture: assets/astera/textures/effects/${slug}.png      (← content/textures/animations/${slug}.png)
- mcmeta:  assets/astera/textures/effects/${slug}.png.mcmeta (← content/textures/animations/${slug}.mcmeta.json)
- model:   assets/astera/models/item/effects/${slug}.json   (← content/models/effects/${slug}.model.json)

リソースパックの \`assets/astera/\` 以下に配置してください。

## 仕様
- ${graph.size[0]}×${graph.size[1]} px / ${graph.frames} frames / ${graph.frame_time_ticks} tick per frame (≈ ${fps} fps)
- ループ: ${graph.loop ? 'はい' : 'いいえ'}

## 召喚コマンド (Java 1.21.4+)

\`\`\`
/${cmd}
\`\`\`

別位置に置きたい場合は \`~ ~1 ~\` を変更してください。
billboard モードを変えたい場合は \`billboard:"center"\` を
\`fixed\` / \`vertical\` / \`horizontal\` に切り替え。

## 削除

\`\`\`
/kill @e[type=minecraft:item_display,nbt={item:{components:{"minecraft:item_model":"astera:effects/${slug}"}}}]
\`\`\`

このコマンドは「同じ effect の item_display」だけを消すので、他のホログラムは残ります。

---
Generated by Astera Studio @ ${new Date().toISOString()}
`
}
