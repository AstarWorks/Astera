"""Bake a named static pose (content/poses/<group>/<name>.yaml) into a scratch PERFORMANCE skill so it can be filmed in the
real client (make vfx-shot) and rendered by the preview (make skill-preview) from the same camera.

usage: python3 tools/pose-solve/bake_pose.py content/poses/greatsword/deep-coil.yaml [--ticks 40]

Writes (all named pose-<group>-<name>, marked generated; delete them when done):
  content/animations/pose-<..>.yaml  static body (one key per channel)
  content/vfx/pose-<..>.yaml         the performance: body + main-hand weapon rig with the pose's wrist
  content/skills/pose-<..>.yaml      a no-damage skill that plays it (cast with `astera skill cast <id> Caster --force`)
Also prints the rig-frame landmarks (rigmodel.fk) so the numbers can be checked before a capture.
"""
from __future__ import annotations

import argparse
import pathlib
import sys

import yaml

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))
import rigmodel as RM  # noqa: E402


def fmt(v) -> str:
    return "[" + ", ".join(("%g" % float(x)) for x in v) + "]"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("pose")
    ap.add_argument("--ticks", type=int, default=40)
    a = ap.parse_args()
    src = pathlib.Path(a.pose)
    doc = yaml.safe_load(src.read_text())
    sid = "pose-" + doc["id"].replace("/", "-")
    n = a.ticks
    head = f"# GENERATED by tools/pose-solve/bake_pose.py from {src.as_posix()} (scratch, static pose). Do not hand-edit.\n"

    lines = [head + f"id: {sid}", f"length_ticks: {n}", "loop: false", "lock_movement: true", "blend_in_ticks: 0", "blend_out_ticks: 0"]
    if doc.get("two_hand_grip"):
        lines.append("two_hand_grip: true")
    lines.append("bones:")
    for bone, ch in (doc.get("bones") or {}).items():
        lines.append(f"  {bone}:")
        for k, v in ch.items():
            lines.append(f"    {k}:")
            lines.append(f"      - {{ t: 0, v: {fmt(v)} }}")
    root = doc.get("root") or {}
    if root:
        lines.append("root:")
        for k, v in root.items():
            lines.append(f"  {k}:")
            lines.append(f"    - {{ t: 0, v: {fmt(v)} }}")
    (ROOT / "content/animations" / f"{sid}.yaml").write_text("\n".join(lines) + "\n")

    wrist = doc.get("wrist", [0, 0, 0])
    vfx = f"""{head}id: {sid}
duration_ticks: {n}
orient: yaw
follow: true
attach_to_anchor: true
sample_ticks: 1
replace_group: {sid}
body: {sid}
rigs:
- id: weapon
  pivot: [0, 0, 0]
  parent: right_hand
  weapon: main_hand
  weapon_tip: [0.0, 1.3789, 1.0769]
  weapon_edge: [0.0, -0.6155, 0.7881]
  swing:
  - {{ t: 0, rotate: {fmt(wrist)} }}
"""
    (ROOT / "content/vfx" / f"{sid}.yaml").write_text(vfx)

    skill = f"""{head}id: {sid}
name: {{ ja: "ポーズ {doc['id']}", en: "Pose {doc['id']}" }}
description: {{ ja: "静止ポーズの確認用 (scratch)。", en: "Static pose check (scratch)." }}
archetype: aoe
cooldown_ticks: 1
tags: [ demo, vfx ]
params:
  type: aoe
  radius: 0.1
  falloff: linear
  damage:
    - base: {{ type: literal, value: 0.0 }}
      attribute: physical
phases:
  type: aoe
  cast:
    - type: play_vfx
      targets: {{ type: caster }}
      vfx_id: {sid}
  hit_entity: []
  expire: []
"""
    (ROOT / "content/skills" / f"{sid}.yaml").write_text(skill)

    p = RM.Pose(root_rot=root.get("rotation", [0, 0, 0]), root_pos=root.get("position", [0, 0, 0]), wrist=wrist,
                two_hand_grip=doc.get("two_hand_grip", False),
                bones={b: {k: v for k, v in ch.items()} for b, ch in (doc.get("bones") or {}).items()})
    lm = RM.fk(p)
    w = RM.weapon(p, lm)
    for k in ("hips", "spine", "neck", "joint_r", "joint_l", "hand_r", "hand_l", "ankle_r", "ankle_l"):
        print("%-8s %s" % (k, fmt(lm[k].round(3))))
    print("grip     %s  tip %s" % (fmt(w["grip"].round(3)), fmt(w["tip"].round(3))))
    print(f"wrote {sid} (animation, vfx, skill)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
