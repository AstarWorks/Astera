// Embeds content/textures/generated/items/*.png (Astera item art) as data URIs so the static viewer can decode them
// from file:// without tainting canvases, and every bitmap font of content/fonts/** (ADR-0239 particle sprites: font
// `astera:<tree>`) with its provider image and vanilla glyph metrics (display-math.js bitmapProvider).
// Run by `bun run build`; output src/generated/*.js is not committed.
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { bitmapProvider } from '../src/display-math.js';
import { decodePng } from './png.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const content = resolve(root, '../../content');
mkdirSync(join(root, 'src/generated'), { recursive: true });

const dir = join(content, 'textures/generated/items');
const out = {};
for (const f of readdirSync(dir).filter((x) => x.endsWith('.png') && !x.startsWith('gui-')).sort()) {
  out[f.replace(/\.png$/, '')] = 'data:image/png;base64,' + readFileSync(join(dir, f)).toString('base64');
}
writeFileSync(join(root, 'src/generated/astera-items.js'), `// generated by scripts/embed-sprites.mjs\nexport const ASTERA_ITEMS = ${JSON.stringify(out)};\n`);
console.log(`embedded ${Object.keys(out).length} item sprites`);

// content/fonts/<tree>.json ships as assets/astera/font/<tree>.json (ResourcePackBuilder); `astera:<path>` textures
// resolve to content/textures/<path>. Other namespaces / provider types are left to the default-font approximation.
const fontsDir = join(content, 'fonts');
const walk = (d) => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]));
const fonts = {};
for (const file of walk(fontsDir).filter((f) => f.endsWith('.json')).sort()) {
  const id = 'astera:' + relative(fontsDir, file).replace(/\\/g, '/').replace(/\.json$/, '');
  const providers = [];
  for (const p of JSON.parse(readFileSync(file, 'utf8')).providers ?? []) {
    if (p.type !== 'bitmap') continue;
    const [ns, path] = p.file.includes(':') ? p.file.split(':') : ['minecraft', p.file];
    if (ns !== 'astera') continue;
    const bytes = readFileSync(join(content, 'textures', path));
    providers.push({ ...bitmapProvider(p, decodePng(bytes)), texture: 'data:image/png;base64,' + bytes.toString('base64') });
  }
  if (providers.length) fonts[id] = { providers };
}
writeFileSync(join(root, 'src/generated/astera-fonts.js'), `// generated by scripts/embed-sprites.mjs\nexport const ASTERA_FONTS = ${JSON.stringify(fonts)};\n`);
console.log(`embedded ${Object.keys(fonts).length} bitmap fonts`);
