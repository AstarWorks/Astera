package com.astarworks.astera.itemart

import org.assertj.core.api.Assertions.assertThat
import org.junit.jupiter.api.Test
import java.awt.image.BufferedImage
import java.nio.file.Files
import java.nio.file.Path

class SpriteTest {

    private val contentDir: Path = Path.of(checkNotNull(System.getProperty("astera.contentDir")))

    /** [n] frames of 64x64 with a 10x10 red square moving 8 px right per frame, plus a green key background. */
    private fun movingBlob(n: Int): List<BufferedImage> = (0 until n).map { i ->
        BufferedImage(64, 64, BufferedImage.TYPE_INT_ARGB).also { img ->
            for (y in 20 until 30) for (x in 4 + i * 8 until 14 + i * 8) img.setRGB(x, y, if (x % 2 == 0) 0xFFE02020.toInt() else 0xFFFF8040.toInt())
        }
    }

    private fun opaqueBounds(img: BufferedImage): IntArray {
        var x0 = 99; var x1 = -1
        for (y in 0 until img.height) for (x in 0 until img.width) if (img.getRGB(x, y) ushr 24 != 0) { x0 = minOf(x0, x); x1 = maxOf(x1, x) }
        return intArrayOf(x0, x1)
    }

    private val options = PixelConverter.Options(colors = 4, outline = false, keepOrphans = true)

    @Test
    fun `a moving blob keeps its offset across converted frames`() {
        val out = PixelConverter.convertFrames(movingBlob(4), options)
        val lefts = out.map { opaqueBounds(it)[0] }
        val steps = lefts.zipWithNext { a, b -> b - a }
        // 8 source px = 7.06 target px per step, so rounding may differ by one pixel but never drift.
        assertThat(steps).allMatch { it in 6..8 }
        assertThat(out).allMatch { it.width == 32 && it.height == 32 }
    }

    @Test
    fun `all frames share one palette and no outline is added`() {
        val out = PixelConverter.convertFrames(movingBlob(3), options)
        val colours = out.map { f -> ItemArt.pixels(f).filter { it ushr 24 != 0 }.toSet() }
        val all = colours.flatten().toSet()
        assertThat(all.size).isLessThanOrEqualTo(4)
        assertThat(all).doesNotContain(Sprite.OUTLINE)
    }

    @Test
    fun `small separate blobs survive conversion`() {
        val img = BufferedImage(128, 128, BufferedImage.TYPE_INT_ARGB)
        for (y in 20 until 90) for (x in 20 until 90) img.setRGB(x, y, 0xFFFFFFFF.toInt())
        for (y in 110 until 116) for (x in 110 until 116) img.setRGB(x, y, 0xFFFFFFFF.toInt())
        val out = PixelConverter.convertFrames(listOf(img), PixelConverter.Options(colors = 2, outline = false, keepOrphans = true)).single()
        val (_, blobs) = PixelConverter.components(PixelConverter.Raster.of(out))
        assertThat(blobs).hasSize(2)
    }

    @Test
    fun `painters are deterministic and every frame but a fade-out last one is non empty`() {
        for (name in ParticlePainters.NAMES) {
            val a = ParticlePainters.frames(name, 6, 32, 0xFFFF9A3C.toInt())
            val b = ParticlePainters.frames(name, 6, 32, 0xFFFF9A3C.toInt())
            a.forEachIndexed { i, f ->
                assertThat(ItemArt.pixels(f)).`as`("$name frame $i").isEqualTo(ItemArt.pixels(b[i]))
                if (i < a.lastIndex) assertThat(ItemArt.pixels(f).count { it ushr 24 != 0 }).`as`("$name frame $i").isGreaterThan(0)
            }
            assertThat(a.first().width).isEqualTo(32)
            assertThat(a.flatMap { ItemArt.pixels(it) }.count { it ushr 24 != 0 }).`as`(name).isGreaterThan(40)
        }
    }

    @Test
    fun `font json lists the frame codepoints as escapes`() {
        val json = SpriteSources.fontJson("spark", 3, 32)
        assertThat(json.trim()).isEqualTo(
            "{\"providers\":[{\"type\":\"bitmap\",\"file\":\"astera:generated/sprites/spark.png\"," +
                "\"ascent\":14,\"height\":32,\"chars\":[\"\\ue000\\ue001\\ue002\"]}]}",
        )
    }

    @Test
    fun `metadata yaml carries the header and counts`() {
        assertThat(SpriteSources.metaYaml("spark", 6, 32)).isEqualTo(
            "# generated by :tools:item-art (ADR-0237); edit content/textures/sources/sprites.yaml\nid: spark\nframes: 6\nsize: 32\n",
        )
    }

    @Test
    fun `generated sprite files match the manifest and the generator is deterministic`() {
        val defs = SpriteSources.load(contentDir)
        val first = SpriteSources.renderAll(contentDir)
        assertThat(first.keys).hasSize(defs.size * 3)
        for ((path, bytes) in first) assertThat(bytes).`as`(path).isEqualTo(SpriteSources.renderAll(contentDir).getValue(path))
        for (def in defs) {
            val strip = ItemArt.decode(first.getValue("${SpriteSources.TEXTURE_DIR}/${def.id}.png"))
            assertThat(strip.width).isEqualTo(def.frames * def.size)
            assertThat(strip.height).isEqualTo(def.size)
            assertThat(Files.isRegularFile(contentDir.resolve("${SpriteSources.META_DIR}/${def.id}.yaml"))).isTrue()
        }
    }
}
