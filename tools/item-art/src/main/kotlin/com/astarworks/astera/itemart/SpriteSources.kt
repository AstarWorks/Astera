package com.astarworks.astera.itemart

import org.yaml.snakeyaml.Yaml
import java.awt.image.BufferedImage
import java.nio.file.Files
import java.nio.file.Path

/**
 * Custom particle sprites (ADR-0239): `content/textures/sources/sprites.yaml` lists, per sprite id, either a
 * code painter ([ParticlePainters]), a row of cells of a sheet, or one image split horizontally into frames.
 * The tool writes a strip PNG, a bitmap font (frame i = U+E000 + i) and runtime metadata per sprite.
 *
 * ```yaml
 * sources:
 *   vfx-v1: { file: sheets/vfx-v1.png, grid: [6, 6] }
 *   slash-strip: { file: images/slash-strip.png }
 * sprites:
 *   spark: { draw: spark, frames: 6, color: "#ffe9a8" }
 *   ember: { from: vfx-v1, row: 0, frames: 6 }
 *   slash: { from: slash-strip, frames: 5 }     # optional: size (32), colors (12), outline (false)
 * ```
 */
internal object SpriteSources {
    const val MANIFEST: String = "${Sources.DIR}/sprites.yaml"
    const val TEXTURE_DIR: String = "textures/generated/sprites"
    const val FONT_DIR: String = "fonts/vfx"
    const val META_DIR: String = "sprites"
    const val FIRST_CODEPOINT: Int = 0xE000
    const val MAX_FRAMES: Int = 256
    const val HEADER: String = "# generated by :tools:item-art (ADR-0239); edit content/textures/sources/sprites.yaml"

    private val KEBAB = Regex("^[a-z][a-z0-9-]*$")

    sealed interface Origin {
        data class Draw(val painter: String, val color: Int) : Origin
        data class Cells(val source: Sources.Source, val row: Int) : Origin
        data class Strip(val source: Sources.Source) : Origin
    }

    data class Def(val id: String, val origin: Origin, val frames: Int, val size: Int, val colors: Int, val outline: Boolean, val quadFont: Boolean = false)

    fun load(contentDir: Path): List<Def> {
        val manifest = contentDir.resolve(MANIFEST)
        if (!Files.isRegularFile(manifest)) return emptyList()
        val doc = Yaml().load<Map<String, Any?>>(Files.readString(manifest)).orEmpty()
        val sources = Sources.parseSources(contentDir, MANIFEST, (doc["sources"] as? Map<*, *>).orEmpty())
        val sprites = (doc["sprites"] as? Map<*, *>).orEmpty()
        return sprites.entries.map { (k, v) ->
            val id = k.toString()
            require(id.matches(KEBAB)) { "$MANIFEST: sprite id must be lower-kebab: $id" }
            val o = requireNotNull(v as? Map<*, *>) { "$MANIFEST: sprite $id is not a map" }
            fun int(key: String): Int? = (o[key] as? Number)?.toInt()
            val size = int("size") ?: 32
            val colors = int("colors") ?: 12
            val outline = o["outline"] as? Boolean ?: false
            val origin: Origin
            val frames: Int
            when {
                o["draw"] != null -> {
                    val painter = o["draw"].toString()
                    require(painter in ParticlePainters.NAMES) { "$MANIFEST: sprite $id: unknown painter '$painter' (${ParticlePainters.NAMES})" }
                    origin = Origin.Draw(painter, parseColor(id, o["color"]?.toString() ?: "#ffffff"))
                    frames = int("frames") ?: 6
                }
                o["from"] != null -> {
                    val name = o["from"].toString()
                    val src = requireNotNull(sources[name]) { "$MANIFEST: sprite $id names unknown source '$name'" }
                    val grid = src.grid
                    if (grid != null) {
                        val row = int("row") ?: 0
                        require(row in 0 until grid.second) { "$MANIFEST: sprite $id: row $row outside sheet '$name'" }
                        frames = int("frames") ?: grid.first
                        require(frames <= grid.first) { "$MANIFEST: sprite $id: $frames frames but sheet '$name' has ${grid.first} columns" }
                        origin = Origin.Cells(src, row)
                    } else {
                        frames = requireNotNull(int("frames")) { "$MANIFEST: sprite $id: a single-image source needs frames" }
                        origin = Origin.Strip(src)
                    }
                }
                else -> error("$MANIFEST: sprite $id needs `draw` or `from`")
            }
            require(frames in 1..MAX_FRAMES) { "$MANIFEST: sprite $id: frames must be 1..$MAX_FRAMES" }
            require(size in 8..512) { "$MANIFEST: sprite $id: size must be 8..512" }
            Def(id, origin, frames, size, colors, outline, o["quad_font"] == true)
        }
    }

    private fun parseColor(id: String, text: String): Int {
        val hex = text.removePrefix("#")
        require(hex.length == 6 && hex.all { it in "0123456789abcdefABCDEF" }) { "$MANIFEST: sprite $id: color must be #rrggbb, got '$text'" }
        return 0xFF000000.toInt() or hex.toInt(16)
    }

    /** The converted / drawn frames of [def], all [Def.size] square with binary alpha. */
    fun render(def: Def): List<BufferedImage> = when (val o = def.origin) {
        is Origin.Draw -> ParticlePainters.frames(o.painter, def.frames, def.size, o.color)
        is Origin.Cells -> convert(def, sheetFrames(o.source.file, o.row, def.frames, o.source.grid!!.first, o.source.grid.second))
        is Origin.Strip -> convert(def, sheetFrames(o.source.file, 0, def.frames, def.frames, 1))
    }

    internal fun convert(def: Def, frames: List<BufferedImage>): List<BufferedImage> = PixelConverter.convertFrames(
        frames,
        PixelConverter.Options(colors = def.colors, size = def.size, outline = def.outline, coverage = SPRITE_COVERAGE, keepOrphans = true),
    )

    private const val SPRITE_COVERAGE = 0.3

    /**
     * Cells of one sheet row, each as the blobs whose centroid lies in the cell, kept in CELL-LOCAL coordinates
     * (padded by a quarter cell so a blob crossing the line stays whole) so frames stay aligned.
     */
    internal fun sheetFrames(file: Path, row: Int, frames: Int, cols: Int, rows: Int): List<BufferedImage> {
        val sheet = Sources.sheet(file)
        val cw = sheet.keyed.w / cols
        val ch = sheet.keyed.h / rows
        val pad = cw / 4
        return (0 until frames).map { col ->
            val x0 = col * cw
            val y0 = row * ch
            val mine = Sources.blobsIn(sheet, x0, y0, x0 + cw, y0 + ch)
            val out = PixelConverter.Raster(cw + 2 * pad, ch + 2 * pad)
            for (y in 0 until out.h) for (x in 0 until out.w) out[x, y] = mine[x0 - pad + x, y0 - pad + y]
            if (sheet.background?.let(::isGreen) == true) despill(out)
            out.image()
        }
    }

    private fun isGreen(c: Int): Boolean {
        val r = c shr 16 and 0xFF; val g = c shr 8 and 0xFF; val b = c and 0xFF
        return g > r + 80 && g > b + 80
    }

    /** Anti-aliased edges of a green-screen sheet keep a green cast the keyer misses: drop green-dominant pixels. */
    private fun despill(r: PixelConverter.Raster) {
        for (i in r.px.indices) {
            val c = r.px[i]
            if (c ushr 24 == 0) continue
            val g = c shr 8 and 0xFF
            if (g - maxOf(c shr 16 and 0xFF, c and 0xFF) > GREEN_CAST) r.px[i] = 0
        }
    }

    private const val GREEN_CAST = 24

    // ---- generated files -------------------------------------------------------------------------------

    /**
     * Frames side by side. Every frame whose last column is empty gets a [WIDTH_PIN] pixel at its bottom-right corner:
     * vanilla `BitmapProvider` sets a glyph's advance from its rightmost pixel with alpha != 0, and a TextDisplay centres
     * the line by that advance while drawing the full cell from the pen - so without the pin each frame would shift by
     * half its empty right margin (up to 8 px, jittering through the flipbook). Alpha 1/255 is below the text shader's
     * 0.1 discard, so the pin never draws.
     */
    fun strip(frames: List<BufferedImage>): BufferedImage {
        val size = frames.first().width
        val img = BufferedImage(size * frames.size, size, BufferedImage.TYPE_INT_ARGB)
        val g = img.createGraphics()
        try { frames.forEachIndexed { i, f -> g.drawImage(f, i * size, 0, null) } } finally { g.dispose() }
        for (i in frames.indices) {
            val x = i * size + size - 1
            if ((0 until size).none { y -> img.getRGB(x, y) ushr 24 != 0 }) img.setRGB(x, size - 1, WIDTH_PIN)
        }
        return img
    }

    /** Invisible width pin (ARGB, alpha 1): see [strip]. */
    const val WIDTH_PIN: Int = 0x01000000

    /** Bitmap font JSON; the codepoints are written as \\u escapes so the file stays plain ASCII. */
    fun fontJson(id: String, frames: Int, size: Int, ascent: Int = size / 2 - 2): String {
        val chars = (0 until frames).joinToString("") { "\\u%04x".format(FIRST_CODEPOINT + it) }
        return "{\"providers\":[{\"type\":\"bitmap\",\"file\":\"${ItemArt.NAMESPACE}:generated/sprites/$id.png\"," +
            "\"ascent\":$ascent,\"height\":$size,\"chars\":[\"$chars\"]}]}\n"
    }

    fun metaYaml(id: String, frames: Int, size: Int): String = "$HEADER\nid: $id\nframes: $frames\nsize: $size\n"

    /** All generated sprite files keyed by path relative to the content dir. */
    fun renderAll(contentDir: Path): Map<String, ByteArray> {
        val files = sortedMapOf<String, ByteArray>()
        val defs = load(contentDir)
        require(defs.map { it.id }.distinct().size == defs.size) { "$MANIFEST: duplicate sprite ids" }
        for (def in defs) {
            val frames = render(def)
            files["$TEXTURE_DIR/${def.id}.png"] = ItemArt.png(strip(frames))
            files["$FONT_DIR/${def.id}.json"] = fontJson(def.id, frames.size, def.size).toByteArray()
            if (def.quadFont) files["$FONT_DIR/${def.id}-quad.json"] = fontJson(def.id, frames.size, 8, 7).toByteArray()
            files["$META_DIR/${def.id}.yaml"] = metaYaml(def.id, frames.size, def.size).toByteArray()
        }
        return files
    }

    /** Generated sprite files on disk that the generator no longer produces. */
    fun orphans(contentDir: Path, keep: Set<String>): List<Path> {
        fun list(dir: String, generated: (Path) -> Boolean): List<Path> {
            val d = contentDir.resolve(dir)
            if (!Files.isDirectory(d)) return emptyList()
            return Files.list(d).use { s -> s.filter { Files.isRegularFile(it) && generated(it) }.toList() }
        }
        return (
            list(TEXTURE_DIR) { true } +
                list(FONT_DIR) { it.toString().endsWith(".json") && Files.readString(it).contains("\"${ItemArt.NAMESPACE}:generated/sprites/") } +
                list(META_DIR) { it.toString().endsWith(".yaml") && Files.readString(it).startsWith("# generated by :tools:item-art") }
            ).filter { contentDir.relativize(it).toString().replace('\\', '/') !in keep }
    }
}
