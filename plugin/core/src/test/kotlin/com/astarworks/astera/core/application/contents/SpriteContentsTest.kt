package com.astarworks.astera.core.application.contents

import com.astarworks.astera.core.domain.effect.vfx.SpriteId
import org.assertj.core.api.Assertions.assertThat
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir
import java.nio.file.Files
import java.nio.file.Path

/** `content/sprites` YAML -> [SpriteDefinition] and the [SpriteContents] frame lookup (ADR-0237). */
class SpriteContentsTest {

    @Test
    fun `bootstrap loads generated sprite metadata and answers frame counts`(@TempDir dir: Path) {
        Files.writeString(
            dir.resolve("spark.yaml"),
            "# generated by :tools:item-art (ADR-0237); edit content/textures/sources/sprites.yaml\nid: spark\nframes: 6\nsize: 32\n",
        )
        Files.writeString(dir.resolve("slash.yaml"), "id: slash\nframes: 5\n")
        val contents = SpriteContents()

        val report = contents.bootstrap(dir)

        assertThat(report.loaded).isEqualTo(2)
        assertThat(contents.find(SpriteId("spark"))).isEqualTo(SpriteDefinition(SpriteId("spark"), 6, 32))
        assertThat(contents.find(SpriteId("slash"))?.size).isEqualTo(32)
        assertThat(contents.frames(SpriteId("spark"))).isEqualTo(6)
        assertThat(contents.frames(SpriteId("missing"))).isNull()
    }

    @Test
    fun `a sprite with zero or too many frames is a failed load`(@TempDir dir: Path) {
        Files.writeString(dir.resolve("zero.yaml"), "id: zero\nframes: 0\n")
        Files.writeString(dir.resolve("huge.yaml"), "id: huge\nframes: 257\n")
        Files.writeString(dir.resolve("ok.yaml"), "id: ok\nframes: 1\n")
        val contents = SpriteContents()

        val report = contents.bootstrap(dir)

        assertThat(report.failed).isEqualTo(2)
        assertThat(contents.find(SpriteId("ok"))).isNotNull
        assertThat(contents.find(SpriteId("zero"))).isNull()
    }
}
